def generate_quiz_content(
    lesson_title: str,
    module_title: Optional[str] = None,
    course_title: Optional[str] = None,
    content: str = "",
    summary: Optional[str] = None,
    learning_objectives: Optional[List[str]] = None,
    key_concepts: Optional[List[str]] = None,
    examples: Optional[List[str]] = None,
    misconceptions: Optional[List[str]] = None,
    practice_questions: Optional[List[Any]] = None,
    num_questions: int = 5,
    difficulty: str = "medium",
    passing_score_percentage: int = 70,
    time_limit_minutes: Optional[int] = None,
) -> GeneratedQuiz:
    """
    Generates a complete, validated multiple-choice quiz for a lesson.
    - If Gemini API key is configured and not in TEST_MODE, requests structured JSON from Gemini.
    - If Gemini is unconfigured, rate-limited (HTTP 429), fails, or outputs invalid schema,
      falls back gracefully and deterministically to generate_grounded_fallback_quiz().
    """
    api_key, model_name = get_gemini_config()

    # Offline / Test Mode check
    if not api_key or os.getenv("TEST_MODE") == "true":
        logger.info("Using grounded deterministic quiz generator (offline mode or TEST_MODE).")
        return generate_grounded_fallback_quiz(
            lesson_title=lesson_title,
            module_title=module_title,
            course_title=course_title,
            content=content,
            summary=summary,
            learning_objectives=learning_objectives,
            key_concepts=key_concepts,
            examples=examples,
            misconceptions=misconceptions,
            practice_questions=practice_questions,
            num_questions=num_questions,
            difficulty=difficulty,
            passing_score_percentage=passing_score_percentage,
            time_limit_minutes=time_limit_minutes,
        )

    logger.info("Invoking Gemini model '%s' to generate assessment for '%s'...", model_name, lesson_title)

    # Format lesson educational material for context
    context_sections = []
    if summary:
        context_sections.append(f"Summary:\n{summary}")
    if learning_objectives:
        context_sections.append("Learning Objectives:\n" + "\n".join(f"- {o}" for o in learning_objectives))
    if key_concepts:
        context_sections.append("Key Concepts:\n" + "\n".join(f"- {c}" for c in key_concepts))
    if examples:
        context_sections.append("Illustrative Examples:\n" + "\n".join(f"- {e}" for e in examples))
    if misconceptions:
        context_sections.append("Common Misconceptions (use to craft plausible distractors):\n" + "\n".join(f"- {m}" for m in misconceptions))
    if practice_questions:
        pq_texts = []
        for pq in practice_questions:
            if isinstance(pq, dict):
                pq_texts.append(f"- Q: {pq.get('question')} | A: {pq.get('answer')} | Exp: {pq.get('explanation')}")
        if pq_texts:
            context_sections.append("Lesson Practice Questions:\n" + "\n".join(pq_texts))
    if content:
        context_sections.append(f"Main Lesson Text:\n{content[:4000]}")

    formatted_context = "\n\n---\n\n".join(context_sections)

    system_instruction = (
        "You are an expert educational assessment creator and instructional designer. "
        "Create a rigorous, multiple-choice quiz based EXCLUSIVELY on the provided lesson material.\n\n"
        "STRICT REQUIREMENTS:\n"
        f"1. Generate exactly {num_questions} questions.\n"
        f"2. Every question must be at '{difficulty}' difficulty level.\n"
        "3. Every question must have EXACTLY 4 options.\n"
        "4. Every question must have EXACTLY 1 correct answer.\n"
        "5. The 'correct_answer' MUST match one of the four options verbatim.\n"
        "6. Distractors (incorrect choices) must be plausible and preferably target common misconceptions from the lesson.\n"
        "7. Questions must test conceptual understanding and application, not trivial copy-pasting.\n"
        "8. Ground all questions and options strictly in the supplied lesson content. Never invent unrelated facts.\n"
        "9. Tag each question with its relevant concept from the lesson.\n"
        "10. Provide a clear pedagogical explanation justifying why the correct answer is right and why the distractors are wrong.\n"
        "11. Ensure NO duplicate questions.\n\n"
        "Return ONLY a valid JSON object matching this schema:\n"
        "{\n"
        f'  "title": "Quiz: {lesson_title}",\n'
        f'  "description": "Assessment of understanding for {lesson_title}",\n'
        '  "quiz_type": "lesson_quiz",\n'
        f'  "passing_score_percentage": {passing_score_percentage},\n'
        '  "questions": [\n'
        "    {\n"
        '      "question_text": "Clear, challenging question prompt",\n'
        '      "question_type": "multiple_choice",\n'
        '      "options": ["Option A", "Option B", "Option C", "Option D"],\n'
        '      "correct_answer": "Option A",\n'
        '      "explanation": "Why Option A is correct and why distractors are incorrect",\n'
        '      "points": 1,\n'
        f'      "difficulty": "{difficulty}",\n'
        '      "concept": "Relevant concept tag",\n'
        '      "order_number": 1\n'
        "    }\n"
        "  ]\n"
        "}"
    )

    user_prompt = (
        f"Course: {course_title or 'General Course'}\n"
        f"Module: {module_title or 'General Module'}\n"
        f"Lesson Title: {lesson_title}\n"
        f"Difficulty: {difficulty}\n"
        f"Number of Questions: {num_questions}\n\n"
        f"Lesson Educational Content:\n{formatted_context}\n\n"
        f"Generate exactly {num_questions} grounded multiple-choice questions matching the requested JSON structure."
    )

    try:
        raw_json = call_gemini_json(user_prompt, system_instruction=system_instruction)
        # Parse and validate questions list
        raw_questions = raw_json.get("questions", [])
        if not isinstance(raw_questions, list) or len(raw_questions) == 0:
            raise QuizGenerationError("Gemini returned no questions in response payload.")

        validated_questions: List[GeneratedQuestion] = []
        seen_prompts = set()

        for idx, q_raw in enumerate(raw_questions, start=1):
            if not isinstance(q_raw, dict):
                continue
            q_text = str(q_raw.get("question_text", "")).strip()
            if not q_text or q_text.lower() in seen_prompts:
                continue

            opts = q_raw.get("options", [])
            if not isinstance(opts, list) or len(opts) != 4:
                continue

            # Ensure clean string options
            clean_opts = [str(o).strip() for o in opts if str(o).strip()]
            if len(clean_opts) != 4 or len(set(o.lower() for o in clean_opts)) != 4:
                continue

            ans = str(q_raw.get("correct_answer", "")).strip()
            # Match answer to options
            matched_ans = next((o for o in clean_opts if o == ans), None)
            if not matched_ans:
                matched_ans = next((o for o in clean_opts if o.lower() == ans.lower()), None)
            if not matched_ans:
                continue

            expl = str(q_raw.get("explanation", "")).strip()
            if not expl:
                expl = f"Grounding explanation based on the lesson on {lesson_title}."

            concept_tag = str(q_raw.get("concept", "")).strip() or (key_concepts[0] if key_concepts else lesson_title)

            gq = GeneratedQuestion(
                question_text=q_text,
                question_type="multiple_choice",
                options=clean_opts,
                correct_answer=matched_ans,
                explanation=expl,
                points=int(q_raw.get("points", 1)),
                difficulty=str(q_raw.get("difficulty", difficulty)),
                concept=concept_tag,
                order_number=len(validated_questions) + 1,
            )
            validated_questions.append(gq)
            seen_prompts.add(q_text.lower())

            if len(validated_questions) == num_questions:
                break

        if len(validated_questions) < num_questions:
            raise QuizGenerationError(
                f"Gemini output only yielded {len(validated_questions)} valid questions (requested {num_questions})."
            )

        quiz = GeneratedQuiz(
            title=raw_json.get("title") or f"Quiz: {lesson_title}",
            description=raw_json.get("description") or f"Assessment of understanding for '{lesson_title}'",
            quiz_type=raw_json.get("quiz_type", "lesson_quiz"),
            passing_score_percentage=passing_score_percentage,
            time_limit_minutes=time_limit_minutes,
            is_fallback=False,
            questions=validated_questions,
        )
        logger.info("Successfully generated quiz via Gemini for '%s' (%d questions).", lesson_title, len(quiz.questions))
        return quiz

    except Exception as exc:
        logger.warning(
            "Gemini quiz generation failed for '%s': %s. Falling back to deterministic grounded generator.",
            lesson_title,
            exc,
        )
        return generate_grounded_fallback_quiz(
            lesson_title=lesson_title,
            module_title=module_title,
            course_title=course_title,
            content=content,
            summary=summary,
            learning_objectives=learning_objectives,
            key_concepts=key_concepts,
            examples=examples,
            misconceptions=misconceptions,
            practice_questions=practice_questions,
            num_questions=num_questions,
            difficulty=difficulty,
            passing_score_percentage=passing_score_percentage,
            time_limit_minutes=time_limit_minutes,
        )
