"""
ai/quiz_generator.py - Grounded AI Assessment & Quiz Generator.

Generates rigorous, educational, multiple-choice quizzes grounded strictly
in lesson educational content.
- Uses Google Gemini (via call_gemini_json) with structured JSON enforcement.
- Provides a robust deterministic offline fallback when Gemini is unavailable,
  unconfigured, rate-limited (HTTP 429), or when test mode is active.
"""

import json
import logging
import os
import re
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field, field_validator, model_validator

from .llm_client import call_gemini_json, get_gemini_config, LLMKeyMissingError, LLMError

logger = logging.getLogger("lms.ai.quiz_generator")


class QuizGenerationError(Exception):
    """Raised when quiz generation fails or output cannot be validated."""
    pass


# ---------------------------------------------------------------------------
# Pydantic Schemas for Internal Validation
# ---------------------------------------------------------------------------

class GeneratedQuestion(BaseModel):
    """Represents a validated question generated by AI or deterministic fallback."""
    question_text: str = Field(..., min_length=5, description="Question prompt")
    question_type: str = Field(default="multiple_choice", description="Question type")
    options: List[str] = Field(..., description="List of exactly 4 choices")
    correct_answer: str = Field(..., description="The correct answer matching one of the options")
    explanation: str = Field(..., min_length=5, description="Pedagogical explanation")
    points: int = Field(default=1, ge=1, description="Point value")
    difficulty: str = Field(default="medium", description="Question difficulty")
    concept: Optional[str] = Field(None, description="Domain concept tested")
    order_number: int = Field(default=1, ge=1, description="Display sequence order")

    @field_validator("options")
    @classmethod
    def validate_options(cls, v: Any) -> List[str]:
        if not isinstance(v, list) or len(v) != 4:
            raise ValueError(f"Question must have exactly 4 options; received {len(v) if isinstance(v, list) else type(v)}")
        cleaned = [str(opt).strip() for opt in v if str(opt).strip()]
        if len(cleaned) != 4:
            raise ValueError("All 4 options must be non-empty strings.")
        # Ensure all 4 options are unique
        if len(set(opt.lower() for opt in cleaned)) != 4:
            raise ValueError(f"All 4 options must be unique; received: {cleaned}")
        return cleaned

    @model_validator(mode="after")
    def validate_correct_answer_in_options(self) -> "GeneratedQuestion":
        target = self.correct_answer.strip()
        # Direct exact match
        for opt in self.options:
            if opt == target:
                self.correct_answer = opt
                return self
        # Case-insensitive match fallback
        for opt in self.options:
            if opt.lower() == target.lower():
                self.correct_answer = opt
                return self
        raise ValueError(
            f"correct_answer '{self.correct_answer}' does not match any of the 4 options: {self.options}"
        )


class GeneratedQuiz(BaseModel):
    """Complete validated quiz structure ready for database persistence."""
    title: str = Field(..., min_length=2, description="Quiz title")
    description: Optional[str] = Field(None, description="Quiz description or instructions")
    quiz_type: str = Field(default="lesson_quiz", description="Type of quiz")
    passing_score_percentage: int = Field(default=70, ge=1, le=100)
    time_limit_minutes: Optional[int] = Field(None, ge=1)
    is_fallback: bool = Field(default=False)
    questions: List[GeneratedQuestion] = Field(default_factory=list)

    @field_validator("questions")
    @classmethod
    def validate_unique_questions(cls, v: List[GeneratedQuestion]) -> List[GeneratedQuestion]:
        if not v:
            raise ValueError("Quiz must contain at least one question.")
        seen = set()
        unique_questions = []
        for q in v:
            norm = q.question_text.strip().lower()
            if norm in seen:
                logger.warning("Duplicate question filtered out: %s", q.question_text)
                continue
            seen.add(norm)
            unique_questions.append(q)
        if not unique_questions:
            raise ValueError("Quiz has no unique questions after deduplication.")
        # Re-index order numbers sequentially
        for idx, q in enumerate(unique_questions, start=1):
            q.order_number = idx
        return unique_questions


