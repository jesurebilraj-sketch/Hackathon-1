def _clean_text_sentences(text: str) -> List[str]:
    """Splits raw text into clean, substantive educational sentences."""
    if not text:
        return []
    # Remove excessive whitespace
    cleaned = re.sub(r'\s+', ' ', text).strip()
    raw_sentences = re.split(r'(?<=[.!?])\s+', cleaned)
    valid_sentences = []
    for s in raw_sentences:
        s = s.strip()
        if len(s) >= 20 and s[0].isupper() and s.endswith(('.', '!', '?')):
            valid_sentences.append(s)
    return valid_sentences


def _rotate_options(correct_answer: str, distractors: List[str], target_index: int) -> List[str]:
    """
    Combines correct_answer with 3 distractors and places correct_answer
    at target_index (0, 1, 2, or 3) to vary answer keys deterministically.
    """
    opts = list(distractors[:3])
    idx = target_index % 4
    opts.insert(idx, correct_answer)
    return opts


def generate_grounded_fallback_quiz(
    lesson_title: str,
    module_title: Optional[str] = None,
    course_title: Optional[str] = None,
    content: str = "",
    summary: Optional[str] = None,
    learning_objectives: Optional[List[str]] = None,
    key_concepts: Optional[List[str]] = None,
    examples: Optional[List[str]] = None,
    misconceptions: Optional[List[str]] = None,
    practice_questions: Optional[List[Any]] = None,
    num_questions: int = 5,
    difficulty: str = "medium",
    passing_score_percentage: int = 70,
    time_limit_minutes: Optional[int] = None,
) -> GeneratedQuiz:
    """
    Generates a high-quality, strictly grounded multiple-choice quiz offline
    using lesson components: practice questions, key concepts, misconceptions,
    and learning objectives.

    Guarantees:
    - Exactly 4 unique options per question.
    - Exactly 1 correct answer belonging to the options.
    - No duplicate questions.
    - Grounded in source data; never invents unrelated facts.
    - is_fallback=True.
    """
    logger.info("Generating deterministic fallback assessment for lesson '%s'...", lesson_title)

    # Normalize inputs
    concepts = [c.strip() for c in (key_concepts or []) if isinstance(c, str) and c.strip()]
    miscons = [m.strip() for m in (misconceptions or []) if isinstance(m, str) and m.strip()]
    objectives = [o.strip() for o in (learning_objectives or []) if isinstance(o, str) and o.strip()]
    sentences = _clean_text_sentences(content)
    if not sentences and summary:
        sentences = _clean_text_sentences(summary)

    # Normalize practice questions
    norm_practice: List[Dict[str, str]] = []
    for pq in (practice_questions or []):
        if isinstance(pq, dict) and "question" in pq and "answer" in pq:
            norm_practice.append({
                "question": str(pq["question"]).strip(),
                "answer": str(pq["answer"]).strip(),
                "explanation": str(pq.get("explanation") or f"This is grounded directly in the lesson on {lesson_title}.").strip(),
            })
        elif hasattr(pq, "question") and hasattr(pq, "answer"):
            norm_practice.append({
                "question": str(pq.question).strip(),
                "answer": str(pq.answer).strip(),
                "explanation": str(getattr(pq, "explanation", "") or f"This is grounded directly in the lesson on {lesson_title}.").strip(),
            })

    # Plausible grounded fallback distractor templates
    # Formulated to be realistic, educational distractor alternatives
    contextual_distractor_pool = [
        "It applies only when explicitly formalized in a written agreement between both parties.",
        "It is evaluated strictly by the subjective intent of the initiator rather than the resulting impact.",
        "It is restricted solely to senior management and does not apply to peers, clients, or contractors.",
        "It can be safely disregarded if no formal objection is immediately voiced.",
        "It operates independently of any workplace policies, standards, or surrounding guidelines.",
        "It requires prior disciplinary history before any formal reporting or action may be initiated.",
        "It only occurs when physical actions take place, excluding verbal or non-verbal communication.",
        "It is considered fully acceptable if conducted offsite outside standard working hours.",
    ]

    # Combine distractor sources
    all_distractor_candidates: List[str] = []
    # 1. Misconceptions are prime distractor material (testing misconceptions)
    for m in miscons:
        if m not in all_distractor_candidates:
            all_distractor_candidates.append(m)
    # 2. Other practice question answers
    for p in norm_practice:
        if p["answer"] not in all_distractor_candidates:
            all_distractor_candidates.append(p["answer"])
    # 3. Contextual distractor pool
    for d in contextual_distractor_pool:
        if d not in all_distractor_candidates:
            all_distractor_candidates.append(d)

    questions_built: List[GeneratedQuestion] = []
    seen_question_prompts = set()

    def add_question(
        prompt: str,
        correct_ans: str,
        explanation: str,
        concept_tag: Optional[str] = None,
        custom_distractors: Optional[List[str]] = None,
    ) -> bool:
        norm_prompt = prompt.strip().lower()
        if norm_prompt in seen_question_prompts:
            return False

        # Select 3 unique distractors not matching correct_ans
        distractors: List[str] = []
        candidate_list = (custom_distractors or []) + all_distractor_candidates
        for cand in candidate_list:
            cand_clean = cand.strip()
            if (
                cand_clean.lower() != correct_ans.strip().lower()
                and cand_clean.lower() not in [d.lower() for d in distractors]
            ):
                distractors.append(cand_clean)
            if len(distractors) == 3:
                break

        # If still fewer than 3 distractors, pull unique contextual fallbacks
        if len(distractors) < 3:
            for fallback_d in contextual_distractor_pool:
                if (
                    fallback_d.lower() != correct_ans.strip().lower()
                    and fallback_d.lower() not in [d.lower() for d in distractors]
                ):
                    distractors.append(fallback_d)
                if len(distractors) == 3:
                    break

        if len(distractors) < 3:
            return False

        order_idx = len(questions_built) + 1
        options = _rotate_options(correct_ans, distractors, order_idx - 1)

        try:
            q_obj = GeneratedQuestion(
                question_text=prompt.strip(),
                question_type="multiple_choice",
                options=options,
                correct_answer=correct_ans.strip(),
                explanation=explanation.strip(),
                points=1,
                difficulty=difficulty,
                concept=concept_tag or lesson_title,
                order_number=order_idx,
            )
            questions_built.append(q_obj)
            seen_question_prompts.add(norm_prompt)
            return True
        except Exception as exc:
            logger.warning("Failed to validate fallback question '%s': %s", prompt, exc)
            return False

    # -----------------------------------------------------------------------
    # Strategy 1: Build from practice questions
    # -----------------------------------------------------------------------
    for pq in norm_practice:
        if len(questions_built) >= num_questions:
            break
        # Formulate concept tag from question or concepts
        matched_concept = next(
            (c for c in concepts if c.lower() in pq["question"].lower() or c.lower() in pq["answer"].lower()),
            concepts[0] if concepts else lesson_title,
        )
        add_question(
            prompt=pq["question"],
            correct_ans=pq["answer"],
            explanation=pq["explanation"],
            concept_tag=matched_concept,
        )

    # -----------------------------------------------------------------------
    # Strategy 2: Build from key concepts
    # -----------------------------------------------------------------------
    for idx, concept in enumerate(concepts):
        if len(questions_built) >= num_questions:
            break
        # Look for sentence defining or explaining this concept
        def_sentence = next(
            (s for s in sentences if concept.lower() in s.lower() and len(s) > 25),
            None,
        )
        if def_sentence:
            prompt = f"In the context of '{lesson_title}', which of the following best explains or defines '{concept}'?"
            correct_ans = def_sentence
            explanation = f"In this lesson, '{concept}' is explicitly described: {def_sentence}"
        else:
            prompt = f"Which of the following statements is TRUE regarding the core concept of '{concept}'?"
            correct_ans = f"'{concept}' is a key instructional principle analyzed in {lesson_title}."
            explanation = f"The lesson examines '{concept}' as an essential domain concept."

        # Use other concepts as distractors
        alt_concept_distractors = []
        for other_c in concepts:
            if other_c.lower() != concept.lower():
                alt_concept_distractors.append(
                    f"It refers strictly to '{other_c}', having no bearing on other aspects of {lesson_title}."
                )

        add_question(
            prompt=prompt,
            correct_ans=correct_ans,
            explanation=explanation,
            concept_tag=concept,
            custom_distractors=alt_concept_distractors,
        )

    # -----------------------------------------------------------------------
    # Strategy 3: Build from misconceptions (Identify false statements)
    # -----------------------------------------------------------------------
    for m in miscons:
        if len(questions_built) >= num_questions:
            break
        prompt = f"Which of the following represents a common MISCONCEPTION identified in the lesson on '{lesson_title}'?"
        correct_ans = m
        grounding = sentences[0] if sentences else f"the established standards of {lesson_title}"
        explanation = f"This statement is a common misconception identified in the lesson. In reality, {grounding}"

        # True statements as distractors
        true_distractors = []
        for obj in objectives:
            true_distractors.append(f"A core objective is to {obj.lower() if obj.startswith(('To ', 'Understand', 'Identify')) else obj}.")
        for s in sentences[:2]:
            if s.lower() != m.lower():
                true_distractors.append(s)

        matched_concept = next(
            (c for c in concepts if c.lower() in m.lower()),
            concepts[0] if concepts else lesson_title,
        )
        add_question(
            prompt=prompt,
            correct_ans=correct_ans,
            explanation=explanation,
            concept_tag=matched_concept,
            custom_distractors=true_distractors,
        )

    # -----------------------------------------------------------------------
    # Strategy 4: Build from learning objectives
    # -----------------------------------------------------------------------
    for obj in objectives:
        if len(questions_built) >= num_questions:
            break
        prompt = f"According to the lesson on '{lesson_title}', which of the following is a primary learning objective?"
        correct_ans = obj
        explanation = f"'{obj}' is explicitly defined as a fundamental learning goal for this lesson."
        add_question(
            prompt=prompt,
            correct_ans=correct_ans,
            explanation=explanation,
            concept_tag=concepts[0] if concepts else lesson_title,
        )

    # -----------------------------------------------------------------------
    # Strategy 5: Build from substantive sentences if still under target
    # -----------------------------------------------------------------------
    for s in sentences:
        if len(questions_built) >= num_questions:
            break
        prompt = f"Based on the educational text of '{lesson_title}', which of the following statements is accurate?"
        correct_ans = s
        explanation = f"This statement reflects the factual guidance provided in the lesson content: \"{s}\""
        add_question(
            prompt=prompt,
            correct_ans=correct_ans,
            explanation=explanation,
            concept_tag=concepts[0] if concepts else lesson_title,
        )

    if not questions_built:
        # Ultimate fail-safe fallback question grounded in lesson title
        prompt = f"What is the primary instructional focus of the lesson titled '{lesson_title}'?"
        correct_ans = f"Understanding the core definitions, guidelines, and principles of {lesson_title}."
        explanation = f"The entire lesson is dedicated to establishing clear principles for {lesson_title}."
        add_question(
            prompt=prompt,
            correct_ans=correct_ans,
            explanation=explanation,
            concept_tag=lesson_title,
        )

    return GeneratedQuiz(
        title=f"Quiz: {lesson_title}",
        description=f"Assessment of understanding for '{lesson_title}'",
        quiz_type="lesson_quiz",
        passing_score_percentage=passing_score_percentage,
        time_limit_minutes=time_limit_minutes,
        is_fallback=True,
        questions=questions_built[:num_questions],
    )


